# ---------------------------------------------------------------- 1. Bambu: a stop is not a failure


@pytest.fixture
def bambu(tls_cert):
    rig = make_rig("bambu", tls_cert)
    yield rig
    for c in rig.closers:
        c()


def test_bambu_failed_after_a_user_stop_is_cancelled_not_an_error(bambu, tmp_path):
    a = bambu.adapter()
    job = upload_job(bambu, tmp_path)
    start_print(bambu, a, job)
    a.cancel()
    # The fake answers like the firmware: gcode_state FAILED with the user cancel print_error.
    assert bambu.fake.report()["print"]["gcode_state"] == "FAILED"
    st = a.status()
    assert st.state == "cancelled"
    assert "error" not in st.message
    # Some firmware leaves print_error at 0 after a stop; that is a cancel too.
    bambu.fake.print_error = 0
    assert a.status().state == "cancelled"
    # FAILED is kept until the next print, and a cancelled printer can start one.
    second = upload_job(bambu, tmp_path, "two.gcode", RIG_GCODE + b"G1 X5\n")
    start_print(bambu, a, second)
    assert a.status().state == "printing"


def test_bambu_real_failure_stays_an_error(bambu, tmp_path):
    a = bambu.adapter()
    start_print(bambu, a, upload_job(bambu, tmp_path))
    bambu.brain.state = "error"  # FAILED with a nonzero, non-cancel print_error
    st = a.status()
    assert st.state == "error" and st.message.startswith("print_error ")
    # FAILED, print_error 0, but an HMS fault: still an error.
    bambu.fake.print_error = 0
    bambu.fake.hms = [{"attr": 0x07008000, "code": 0x00020001}]
    st = a.status()
    assert st.state == "error" and "HMS 07008000-00020001" in st.message
    # A user cancel code does not hide an HMS fault.
    bambu.fake.print_error = 0x0300400C
    assert a.status().state == "error"
    # A nonzero print_error while idle is an error too.
    bambu.fake.hms = []
    bambu.fake.print_error = 0x0500C011
    bambu.brain.state = "idle"
    assert a.status().state == "error"


# ---------------------------------------------------------------- 2. Klipper: plain G1 E retracts

# Stands in for PrusaSlicer's retraction output: --use-firmware-retraction makes it write G10/G11,
# otherwise it retracts with G1 E moves of --retract-length (relative E with --use-relative-e-distances).
FAKE_PRUSA = """#!{py}
import json, sys, pathlib
args = sys.argv[1:]
pathlib.Path({log!r}).write_text(json.dumps(args))
out = pathlib.Path(args[args.index("--output") + 1])
r = float(args[args.index("--retract-length") + 1])
lines = ["; generated by fake slicer", "M83" if "--use-relative-e-distances" in args else "M82", "G1 X10 Y10 E1"]
if "--use-firmware-retraction" in args:
    lines += ["G10", "G0 X50 Y50", "G11"]
else:
    lines += [f"G1 E-{{r:.2f}} F2100", "G0 X50 Y50", f"G1 E{{r:.2f}} F2100"]
out.write_text("\\n".join(lines + ["G1 X60 Y50 E1"]) + "\\n")
"""

STL = b"solid t\nfacet normal 0 0 1\nouter loop\nvertex 0 0 0\nvertex 10 0 0\nvertex 0 10 0\nendloop\nendfacet\nendsolid t\n"


@pytest.fixture
def prusa(tmp_path, monkeypatch):
    log = tmp_path / "slicer-args.json"
    exe = tmp_path / "prusa-slicer"
    exe.write_text(FAKE_PRUSA.format(py=sys.executable, log=str(log)))
    exe.chmod(exe.stat().st_mode | stat.S_IEXEC)
    monkeypatch.setenv("GANTREL_PRUSASLICER", str(exe))
    return log


@pytest.mark.parametrize("model", ["generic-klipper", "creality-k2"])
@pytest.mark.parametrize("mat", ["PLA", "PETG"])
def test_klipper_profiles_slice_with_plain_retracts_of_retract_mm(prusa, tmp_path, model, mat, capsys):
    brain = fakes.Brain(secret=None)
    srv = fakes.serve_http(brain, fakes.moonraker_routes)
    try:
        assert cli.main(["pair", "k", "--type", "moonraker", "--host", "127.0.0.1", "--port",
                         str(srv.server_address[1]), "--model", model]) == 0
        stl = tmp_path / "part.stl"
        stl.write_bytes(STL)
        capsys.readouterr()
        assert cli.main(["slice", str(stl), "--printer", "k", "--material", mat, "--json"]) == 0
    finally:
        srv.shutdown()
    result = json.loads(capsys.readouterr().out)
    retract = slicing.material(mat).retract_mm
    args = json.loads(prusa.read_text())
    assert "--use-firmware-retraction" not in args
    assert args[args.index("--retract-length") + 1] == str(retract)
    text = open(result["gcode"]).read()
    cmds = [ln.split(";")[0].split() for ln in text.splitlines()]
    assert not any(c and c[0] in ("G10", "G11") for c in cmds)
    assert f"G1 E-{retract:.2f} F2100" in text


def test_orca_overrides_turn_firmware_retraction_off():
    s = slicing.settings(slicing.PRINTERS["creality-k2"], slicing.material("PETG"))
    machine, _, _ = slicing.orca_overrides(s, slicing.PRINTERS["creality-k2"])
    assert machine["use_firmware_retraction"] == "0"
    assert machine["retraction_length"] == ["1.0"]


# ---------------------------------------------------------------- 3. Tokens: spent first, bound to one print


def test_changed_then_restored_file_cannot_reuse_the_start_token(printer, tmp_path):
    job = upload(tmp_path)
    token = safety.mint_token("start", "moon", job.id, job.sha256, job.identity)
    part = tmp_path / "part.gcode"
    part.write_bytes(GCODE + b"M104 S300\n")
    with pytest.raises(SafetyError, match="changed"):
        build(config.get("moon")).start(job, token)
    part.write_bytes(GCODE)  # restored: the file check would pass now
    with pytest.raises(SafetyError, match="already used"):
        build(config.get("moon")).start(job, token)
    assert not printer.started


def test_start_on_the_wrong_printer_voids_the_token(printer, tmp_path):
    job = upload(tmp_path)
    printers = config.load_all()
    printers["moon2"] = config.PrinterConfig(name="moon2", type="moonraker", host="127.0.0.1",
                                             port=printers["moon"].port)
    config.save_all(printers)
    token = safety.mint_token("start", "moon", job.id, job.sha256, job.identity)
    with pytest.raises(SafetyError):
        build(config.get("moon2")).start(job, token)
    with pytest.raises(SafetyError, match="already used"):
        build(config.get("moon")).start(job, token)
    assert not printer.started


def _start_and_pause(printer, tmp_path, name="part.gcode", data=GCODE):
    job = upload(tmp_path, name, data)
    assert app_start(job.id, safety.mint_token("start", "moon", job.id, job.sha256, job.identity)) == 0
    assert cli.main(["pause", "moon"]) == 0
    assert printer.state == "paused"
    return job


def test_a_resume_token_bound_only_to_the_file_name_is_refused(printer, tmp_path, capsys):
    job = _start_and_pause(printer, tmp_path)
    a = build(config.get("moon"))
    by_name = safety.mint_token("resume", "moon", "resume:" + a.status().file, "", a.identity())
    assert app_resume("moon", by_name) == cli.EXIT_SAFETY
    assert "different job" in capsys.readouterr().err
    assert printer.state == "paused"
    # A token for this print, its job record and file hash, resumes it.
    good = safety.mint_token("resume", "moon", "resume:" + job.id, job.sha256, a.identity())
    assert app_resume("moon", good) == 0
    assert printer.state == "printing"


def test_resume_is_refused_for_a_print_gantrel_did_not_upload(printer, tmp_path, capsys):
    printer.put("by-hand.gcode", GCODE)
    assert printer.start("by-hand.gcode")  # a person started it from the printer's screen
    assert cli.main(["pause", "moon"]) == 0
    a = build(config.get("moon"))
    token = safety.mint_token("resume", "moon", "resume:by-hand.gcode", "", a.identity())
    assert app_resume("moon", token) == cli.EXIT_SAFETY
    assert "no job record" in capsys.readouterr().err
    assert printer.state == "paused"
    # The refusal spent the token.
    assert len(list((config.state_dir() / "tokens").glob("*.used"))) == 1


def test_a_resume_token_never_carries_over_to_a_later_print_of_the_same_name(printer, tmp_path):
    from gantrel_printer.adapters.base import resume_binding

    first = _start_and_pause(printer, tmp_path)
    a = build(config.get("moon"))
    old = safety.mint_token("resume", "moon", *resume_binding(a, a.status()), a.identity())
    # That print is cancelled, its file deleted on the printer, and the same file uploaded and started again.
    assert cli.main(["cancel", "moon"]) == 0
    del printer.files[first.remote_name]
    second = _start_and_pause(printer, tmp_path)
    assert second.remote_name == first.remote_name and second.id != first.id
    with pytest.raises(SafetyError, match="different job"):
        a.resume(old)
    assert printer.state == "paused"


def test_a_refused_resume_spends_the_token(printer, tmp_path):
    from gantrel_printer.adapters.base import resume_binding

    _start_and_pause(printer, tmp_path)
    a = build(config.get("moon"))
    token = safety.mint_token("resume", "moon", *resume_binding(a, a.status()), a.identity())
    printer.act("resume")  # a person resumed it on the screen first
    from gantrel_printer.errors import Refused

    with pytest.raises(Refused, match="not paused"):
        a.resume(token)
    printer.act("pause")
    with pytest.raises(SafetyError, match="already used"):
        a.resume(token)
    assert printer.state == "paused"
