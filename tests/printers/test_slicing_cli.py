def test_every_reply_ends_with_next_and_json_carries_it(k2, tmp_path, capsys):
    for argv in (["list"], ["status", "k2"], ["camera", "k2", "--out", str(tmp_path / "c.jpg")], ["profiles"]):
        capsys.readouterr()
        assert cli.main(argv) == 0, argv
        assert capsys.readouterr().out.strip().splitlines()[-1].startswith("NEXT: "), argv
    assert cli.main(["status", "k2", "--json"]) == 0
    data = json.loads(capsys.readouterr().out)
    assert data["state"] == "idle" and data["next"]


def test_upload_refuses_unsafe_remote_names(k2, tmp_path, capsys):
    f = tmp_path / "x.gcode"
    f.write_bytes(b"G28\n")
    assert cli.main(["upload", str(f), "--printer", "k2", "--name", "../../etc/x.gcode"]) == cli.EXIT_ERROR
    assert cli.main(["upload", str(f), "--printer", "k2", "--name", "x.sh"]) == cli.EXIT_ERROR
    assert k2.files == {}
