def test_pair_puts_the_secret_in_the_keyring_not_the_config(tmp_path, monkeypatch):
    brain = fakes.Brain(secret="opk-123456")
    srv = fakes.serve_http(brain, fakes.octoprint_routes)
    import io

    monkeypatch.setattr(sys, "stdin", io.StringIO("opk-123456\n"))
    try:
        assert cli.main(["pair", "octo", "--type", "octoprint", "--host", "127.0.0.1", "--port",
                         str(srv.server_address[1]), "--secret-stdin"]) == 0
    finally:
        srv.shutdown()
    raw = config.config_path().read_text()
    assert "opk-123456" not in raw
    assert config.get_secret("octo") == "opk-123456"
    assert oct(config.config_path().stat().st_mode & 0o777) == "0o600"


def test_pair_with_a_wrong_secret_saves_nothing(monkeypatch):
    brain = fakes.Brain(secret="right")
    srv = fakes.serve_http(brain, fakes.prusalink_routes)
    import io

    monkeypatch.setattr(sys, "stdin", io.StringIO("wrong\n"))
    try:
        assert cli.main(["pair", "mk4", "--type", "prusalink", "--host", "127.0.0.1", "--port",
                         str(srv.server_address[1]), "--secret-stdin"]) == cli.EXIT_ERROR
    finally:
        srv.shutdown()
    assert "mk4" not in config.load_all()
    assert config.get_secret("mk4") is None


