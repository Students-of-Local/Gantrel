FAKE_SLICER = """#!{py}
import json, sys, pathlib
args = sys.argv[1:]
pathlib.Path({log!r}).write_text(json.dumps(args))
out = pathlib.Path(args[args.index("--output") + 1])
temp = args[args.index("--temperature") + 1]
out.write_text("; generated by fake slicer\\n; filament_type = " + args[args.index("--filament-type") + 1]
               + "\\nG28\\nM104 S" + temp + "\\n; estimated printing time (normal mode) = 1h 2m 3s\\n")
"""

STL = b"solid t\nfacet normal 0 0 1\nouter loop\nvertex 0 0 0\nvertex 10 0 0\nvertex 0 10 0\nendloop\nendfacet\nendsolid t\n"


@pytest.fixture
def fake_slicer(tmp_path, monkeypatch):
    log = tmp_path / "slicer-args.json"
    exe = tmp_path / "prusa-slicer"
    exe.write_text(FAKE_SLICER.format(py=sys.executable, log=str(log)))
    exe.chmod(exe.stat().st_mode | stat.S_IEXEC)
    monkeypatch.setenv("GANTREL_PRUSASLICER", str(exe))
    return log


@pytest.fixture
def k2(tmp_path):
    brain = fakes.Brain(secret=None)
    srv = fakes.serve_http(brain, fakes.moonraker_routes)
    assert cli.main(["pair", "k2", "--type", "moonraker", "--host", "127.0.0.1", "--port",
                     str(srv.server_address[1]), "--model", "creality-k2"]) == 0
    yield brain
    srv.shutdown()


def test_k2_pla_profile_values():
    s = slicing.settings(slicing.PRINTERS["creality-k2"], slicing.material("pla"))
    assert s["bed_mm"] == [260, 260] and s["max_height_mm"] == 260
    assert (s["nozzle_c"], s["bed_c"], s["layer_height_mm"], s["perimeters"]) == (215, 60, 0.2, 3)
    assert s["first_layer_speed_mms"] == 30


def test_material_rules():
    open_printer = slicing.PRINTERS["generic-marlin"]
    with pytest.raises(ConfigError, match="needs an enclosed printer"):
        slicing.settings(open_printer, slicing.material("ABS"))
    with pytest.raises(ConfigError, match="direct drive"):
        slicing.settings(open_printer, slicing.material("TPU"))
    tpu = slicing.settings(slicing.PRINTERS["creality-k2"], slicing.material("TPU"))
    assert tpu["infill_speed_mms"] == 30 and tpu["outer_wall_speed_mms"] == 30
    with pytest.raises(ConfigError):
        slicing.material("unobtainium")


def test_every_profile_and_material_combination_is_consistent():
    for p in slicing.PRINTERS.values():
        for m in slicing.MATERIALS.values():
            try:
                s = slicing.settings(p, m)
            except ConfigError:
                assert (m.needs_enclosure and not p.enclosed) or (m.name == "TPU" and not p.direct_drive)
                continue
            assert s["infill_speed_mms"] <= m.max_speed and s["travel_speed_mms"] == p.max_speed
            args = slicing.prusa_args(s, p)
            assert args[args.index("--bed-shape") + 1] == f"0x0,{p.bed[0]}x0,{p.bed[0]}x{p.bed[1]},0x{p.bed[1]}"


def test_slice_for_k2_runs_the_slicer_with_the_profile(k2, tmp_path, fake_slicer, capsys):
    stl = tmp_path / "cube.stl"
    stl.write_bytes(STL)
    assert cli.main(["slice", str(stl), "--printer", "k2", "--material", "PETG"]) == 0
    text = capsys.readouterr().out
    args = json.loads(fake_slicer.read_text())
    assert args[0] == "--export-gcode" and args[-1] == str(stl)
    assert args[args.index("--gcode-flavor") + 1] == "klipper"
    assert args[args.index("--temperature") + 1] == "240"
    assert args[args.index("--bed-temperature") + 1] == "75"
    assert "START_PRINT EXTRUDER_TEMP=" in args[args.index("--start-gcode") + 1]
    gcode = tmp_path / "cube_creality-k2_PETG.gcode"
    assert gcode.exists()
    assert "nozzle_c: 240" in text and "Estimated print time: 1h 2m" in text
    assert text.strip().splitlines()[-1] == f"NEXT: gantrel-printer upload {gcode} --printer k2 --material PETG"


def test_slice_without_a_slicer_explains_what_to_install(k2, tmp_path, monkeypatch, capsys):
    monkeypatch.delenv("GANTREL_PRUSASLICER", raising=False)
    monkeypatch.delenv("GANTREL_ORCASLICER", raising=False)
    monkeypatch.setenv("PATH", str(tmp_path / "empty-bin"))
    monkeypatch.setenv("HOME", str(tmp_path / "home"))
    monkeypatch.setattr(slicing, "MAC_APPS", {"prusaslicer": "/nonexistent", "orcaslicer": "/nonexistent"})
    assert slicing.find_slicers() == {}
    stl = tmp_path / "cube.stl"
    stl.write_bytes(STL)
    assert cli.main(["slice", str(stl), "--printer", "k2"]) == cli.EXIT_ERROR
    err = capsys.readouterr().err
    assert "no slicer is installed" in err and "PrusaSlicer" in err and "OrcaSlicer" in err


