GCODE = b"; filament_type = PLA\n; estimated printing time (normal mode) = 12m 5s\nG28\n"
FAKE_SLICER = """#!{py}
import sys, pathlib
args = sys.argv[1:]
out = pathlib.Path(args[args.index("--output") + 1])
out.write_text("; generated by fake slicer\\n; filament_type = " + args[args.index("--filament-type") + 1]
               + "\\nG28\\n; estimated printing time (normal mode) = 1h 2m 3s\\n")
"""
TOOLS = {"printers", "printer_status", "filaments", "jobs", "camera_snapshot", "plan", "check", "slice", "upload",
         "pause", "cancel", "emergency_stop", "print_start", "print_resume"}


@pytest.fixture
def printer():
    brain = fakes.Brain(secret=None)
    srv = fakes.serve_http(brain, fakes.moonraker_routes)
    assert cli.main(["pair", "moon", "--type", "moonraker", "--host", "127.0.0.1", "--port",
                     str(srv.server_address[1]), "--model", "creality-k2"]) == 0
    yield brain
    srv.shutdown()


@pytest.fixture
def block(tmp_path):
    import shapes
    from gantrel_printer.plan import mesh as pmesh

    stl = tmp_path / "block.stl"
    pmesh.write_stl(stl, shapes.boxes((0, 20, 0, 20, 0, 10)))
    return stl


def test_the_tool_list():
    assert set(tool_names()) == TOOLS


def test_read_tools(printer):
    assert call("printers").data["printers"][0]["name"] == "moon"
    st = call("printer_status", {"printer": "moon"}).data
    assert st["state"] == "idle" and st["next"].startswith("Check the bed")
    slots = call("filaments", {"printer": "moon"}).data["slots"]
    assert slots[0]["slot"] == "ext"
    assert call("jobs").data["jobs"] == []
    r = call("printer_status", {"printer": "nope"})
    assert r.is_error and "no printer named 'nope'" in r.text


def test_camera_snapshot_is_an_image(printer):
    r = call("camera_snapshot", {"printer": "moon"})
    assert not r.is_error
    img = r.raw.content[0]
    assert img.type == "image" and img.mime_type == "image/jpeg"
    assert base64.b64decode(img.data) == fakes.JPEG


def test_camera_snapshot_is_size_capped(printer, monkeypatch):
    from gantrel_mcp import server

    monkeypatch.setattr(server, "SNAPSHOT_MAX", 10)
    r = call("camera_snapshot", {"printer": "moon"})
    assert r.is_error and "over Gantrel's" in r.text


def test_stop_tools(printer, tmp_path):
    printer.put("x.gcode", GCODE)
    printer.state, printer.current = "printing", "x.gcode"
    assert call("pause", {"printer": "moon"}).data["paused"] == "moon"
    assert call("cancel", {"printer": "moon"}).data["cancelled"] == "moon"
    assert call("emergency_stop", {"printer": "moon"}).data["estop"] == "moon"
    assert printer.events == ["pause", "cancel", "estop"]


def test_plan_and_check(printer, block):
    p = call("plan", {"path": str(block), "printer": "creality-k2", "material": "PLA"}).data
    assert p["check"]["ok"] and safety.load_plan(p["plan_id"])["material"] == "PLA"
    c = call("check", {"settings": p["settings"], "printer": "moon", "material": "PLA",
                       "model_path": str(block)}).data
    assert c["ok"] and c["printer"] == "creality-k2" and c["part_orientation"].startswith("as drawn")
    c = call("check", {"settings": p, "printer": "moon", "material": "PLA", "model_path": str(block)}).data
    assert c["ok"] and c["part_orientation"].startswith("turned the plan's way")
    bad = dict(p["settings"], nozzle_c=320)
    c = call("check", {"settings": {"settings": bad}, "printer": "moon", "material": "PLA"}).data
    assert not c["ok"] and c["fails"]
    r = call("plan", {"path": str(block), "printer": "moon", "material": "PLA", "goal": "fast"})
    assert r.is_error and "goal must be one of" in r.text
    r = call("plan", {"path": str(block), "printer": "generic-marlin", "material": "PA-CF"})
    assert not r.is_error and json.loads(r.text).get("refused") is True and "plan_id" not in r.text


def test_slice_then_upload_never_starts(printer, block, tmp_path, monkeypatch):
    exe = tmp_path / "prusa-slicer"
    exe.write_text(FAKE_SLICER.format(py=sys.executable))
    exe.chmod(exe.stat().st_mode | stat.S_IEXEC)
    monkeypatch.setenv("GANTREL_PRUSASLICER", str(exe))
    s = call("slice", {"path": str(block), "printer": "moon", "material": "PETG"}).data
    assert s["gcode"].startswith(str(tmp_path)) and s["material"] == "PETG"
    u = call("upload", {"path": s["gcode"], "printer": "moon"}).data
    assert u["started"] is False and u["material"] == "PETG" and "print_start" in u["next"]
    assert printer.files and not printer.started
    r = call("slice", {"path": str(block), "printer": "moon", "quality": "ultra"})
    assert r.is_error and "quality must be one of" in r.text


# ---------------------------------------------------------------- file path rules


@pytest.fixture
def roots(tmp_path, monkeypatch):
    """HOME and the working folder moved into tmp_path, plus a folder outside both."""
    home, work, outside = tmp_path / "home", tmp_path / "work", tmp_path / "outside"
    for d in (home, work, outside):
        d.mkdir()
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.chdir(work)
    return home, work, outside


def test_files_inside_home_or_the_working_folder_are_allowed(roots):
    home, work, _ = roots
    (home / "a.stl").write_bytes(b"x")
    (work / "b.stl").write_bytes(b"x")
    assert files.checked(str(home / "a.stl"), "model") == home / "a.stl"
    assert files.checked("~/a.stl", "model") == home / "a.stl"
    assert files.checked("b.stl", "model") == work / "b.stl"
    (home / "link.stl").symlink_to(work / "b.stl")  # a link that stays inside is fine
    assert files.checked(str(home / "link.stl"), "model") == work / "b.stl"


def test_files_outside_are_refused(roots):
    home, work, outside = roots
    (outside / "x.gcode").write_bytes(GCODE)
    (home / "out.gcode").symlink_to(outside / "x.gcode")
    (home / "dir").mkdir()
    (home / "dirlink").symlink_to(outside)
    for bad in (str(outside / "x.gcode"), str(home / "out.gcode"), str(home / "dirlink" / "x.gcode"),
                str(home / ".." / "outside" / "x.gcode"), "../outside/x.gcode", "/etc/hostname"):
        with pytest.raises(files.ConfigError, match="outside your home folder"):
            files.checked(bad, "gcode")
    with pytest.raises(files.ConfigError, match="not a regular file"):
        files.checked(str(home / "dir"), "gcode")
    with pytest.raises(files.ConfigError, match="no file at"):
        files.checked(str(home / "missing.gcode"), "gcode")
    for bad in ("", "  ", "a\x00b", None, 5):
        with pytest.raises(files.ConfigError, match="empty or not a path"):
            files.checked(bad, "gcode")


def test_root_is_never_an_allowed_folder(roots, monkeypatch):
    monkeypatch.chdir("/")
    assert all(r != r.parent for r in files.roots())
    with pytest.raises(files.ConfigError, match="outside your home folder"):
        files.checked("/etc/hostname", "gcode")


def test_size_caps(roots):
    home, _, _ = roots
    big_model, big_gcode = home / "big.stl", home / "big.gcode"
    with open(big_model, "wb") as fh:
        fh.truncate(200 * 1024 * 1024 + 1)  # sparse: no disk used
    with open(big_gcode, "wb") as fh:
        fh.truncate(500 * 1024 * 1024 + 1)
    with pytest.raises(files.ConfigError, match="over Gantrel's 200 MB limit for a model"):
        files.checked(str(big_model), "model")
    with pytest.raises(files.ConfigError, match="over Gantrel's 500 MB limit for a sliced file"):
        files.checked(str(big_gcode), "gcode")
    assert files.checked(str(big_model), "gcode") == big_model  # 200 MB is fine for G-code


def test_every_file_tool_applies_the_rules(printer, roots):
    home, _, outside = roots
    (outside / "x.gcode").write_bytes(GCODE)
    (outside / "x.stl").write_bytes(b"solid x\nendsolid x\n")
    (home / "x.gcode").symlink_to(outside / "x.gcode")
    (home / "x.stl").symlink_to(outside / "x.stl")
    for name, args in (("upload", {"path": str(home / "x.gcode"), "printer": "moon"}),
                       ("upload", {"path": str(outside / "x.gcode"), "printer": "moon"}),
                       ("slice", {"path": str(home / "x.stl"), "printer": "moon"}),
                       ("plan", {"path": str(home / "x.stl"), "printer": "moon", "material": "PLA"}),
                       ("check", {"settings": {"nozzle_c": 210}, "printer": "moon", "material": "PLA",
                                  "model_path": str(outside / "x.stl")})):
        r = call(name, args)
        assert r.is_error and "outside your home folder" in r.text, (name, r.text)
    assert printer.files == {}
    assert not os.path.exists(outside / "x_creality-k2_PLA.gcode")
