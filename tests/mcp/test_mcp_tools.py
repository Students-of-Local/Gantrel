@pytest.fixture
def roots(tmp_path, monkeypatch):
    """HOME and the working folder moved into tmp_path, plus a folder outside both."""
    home, work, outside = tmp_path / "home", tmp_path / "work", tmp_path / "outside"
    for d in (home, work, outside):
        d.mkdir()
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.chdir(work)
    return home, work, outside


def test_files_inside_home_or_the_working_folder_are_allowed(roots):
    home, work, _ = roots
    (home / "a.stl").write_bytes(b"x")
    (work / "b.stl").write_bytes(b"x")
    assert files.checked(str(home / "a.stl"), "model") == home / "a.stl"
    assert files.checked("~/a.stl", "model") == home / "a.stl"
    assert files.checked("b.stl", "model") == work / "b.stl"
    (home / "link.stl").symlink_to(work / "b.stl")  # a link that stays inside is fine
    assert files.checked(str(home / "link.stl"), "model") == work / "b.stl"


def test_files_outside_are_refused(roots):
    home, work, outside = roots
    (outside / "x.gcode").write_bytes(GCODE)
    (home / "out.gcode").symlink_to(outside / "x.gcode")
    (home / "dir").mkdir()
    (home / "dirlink").symlink_to(outside)
    for bad in (str(outside / "x.gcode"), str(home / "out.gcode"), str(home / "dirlink" / "x.gcode"),
                str(home / ".." / "outside" / "x.gcode"), "../outside/x.gcode", "/etc/hostname"):
        with pytest.raises(files.ConfigError, match="outside your home folder"):
            files.checked(bad, "gcode")
    with pytest.raises(files.ConfigError, match="not a regular file"):
        files.checked(str(home / "dir"), "gcode")
    with pytest.raises(files.ConfigError, match="no file at"):
        files.checked(str(home / "missing.gcode"), "gcode")
    for bad in ("", "  ", "a\x00b", None, 5):
        with pytest.raises(files.ConfigError, match="empty or not a path"):
            files.checked(bad, "gcode")


def test_root_is_never_an_allowed_folder(roots, monkeypatch):
    monkeypatch.chdir("/")
    assert all(r != r.parent for r in files.roots())
    with pytest.raises(files.ConfigError, match="outside your home folder"):
        files.checked("/etc/hostname", "gcode")


def test_size_caps(roots):
    home, _, _ = roots
    big_model, big_gcode = home / "big.stl", home / "big.gcode"
    with open(big_model, "wb") as fh:
        fh.truncate(200 * 1024 * 1024 + 1)  # sparse: no disk used
    with open(big_gcode, "wb") as fh:
        fh.truncate(500 * 1024 * 1024 + 1)
    with pytest.raises(files.ConfigError, match="over Gantrel's 200 MB limit for a model"):
        files.checked(str(big_model), "model")
    with pytest.raises(files.ConfigError, match="over Gantrel's 500 MB limit for a sliced file"):
        files.checked(str(big_gcode), "gcode")
    assert files.checked(str(big_model), "gcode") == big_model  # 200 MB is fine for G-code


def test_every_file_tool_applies_the_rules(printer, roots):
    home, _, outside = roots
    (outside / "x.gcode").write_bytes(GCODE)
    (outside / "x.stl").write_bytes(b"solid x\nendsolid x\n")
    (home / "x.gcode").symlink_to(outside / "x.gcode")
    (home / "x.stl").symlink_to(outside / "x.stl")
    for name, args in (("upload", {"path": str(home / "x.gcode"), "printer": "moon"}),
                       ("upload", {"path": str(outside / "x.gcode"), "printer": "moon"}),
                       ("slice", {"path": str(home / "x.stl"), "printer": "moon"}),
                       ("plan", {"path": str(home / "x.stl"), "printer": "moon", "material": "PLA"}),
                       ("check", {"settings": {"nozzle_c": 210}, "printer": "moon", "material": "PLA",
                                  "model_path": str(outside / "x.stl")})):
        r = call(name, args)
        assert r.is_error and "outside your home folder" in r.text, (name, r.text)
    assert printer.files == {}
    assert not os.path.exists(outside / "x_creality-k2_PLA.gcode")
