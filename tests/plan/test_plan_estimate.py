ORCA_BBL = """; HEADER_BLOCK_START
; generated by OrcaSlicer 2.2.0 on 2026-11-20 at 10:11:12
; model printing time: 1h 0m 5s; total estimated time: 1h 6m 40s
; total layer number: 100
; HEADER_BLOCK_END
; filament used [mm] = 100.00, 200.00
; filament used [g] = 0.30, 0.60
; total filament used [g] = 0.90
"""


def test_reads_prusaslicer():
    g = est.parse_slicer_gcode(PRUSA)
    assert g["slicer"] == "PrusaSlicer" and g["seconds"] == 17 * 60 + 27
    assert g["first_layer_seconds"] == 117
    assert g["filament_mm"] == pytest.approx(676.57) and g["filament_g"] == pytest.approx(1.76)
    assert g["filament_cm3"] == pytest.approx(1.63)


def test_reads_orcaslicer_both_forms():
    g = est.parse_slicer_gcode(ORCA)
    assert g["slicer"] == "OrcaSlicer" and g["seconds"] == 3723 and g["filament_g"] == pytest.approx(3.68)
    b = est.parse_slicer_gcode(ORCA_BBL)
    assert b["seconds"] == 4000 and b["model_seconds"] == 3605
    assert b["filament_mm"] == pytest.approx(300) and b["filament_g"] == pytest.approx(0.90)


def test_slicing_time_regex_misses_the_bambu_form():
    # Why plan/estimate.py has its own reader: slicing._TIME_RE stops at "model printing time".
    m = slicing._TIME_RE.search(ORCA_BBL)
    assert m is None or slicing.parse_duration(m.group(1)) != 4000


def test_nothing_to_read():
    assert est.parse_slicer_gcode("G28\nG1 X10\n") == {}
