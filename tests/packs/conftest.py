class NoKeyring(keyring.backend.KeyringBackend):
    """Fails the test on any keyring access: packs must never read a secret."""

    priority = 1

    def get_password(self, service, username):
        raise AssertionError(f"keyring read: {service} {username}")

    def set_password(self, service, username, password):
        raise AssertionError("keyring write")

    def delete_password(self, service, username):
        raise AssertionError("keyring delete")


